-- Shared lesson content. Administrators are provisioned via trusted Auth app_metadata only.
create table if not exists public.lesson_catalog (
  id integer generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 80),
  description text not null check (char_length(description) between 1 and 240),
  difficulty text not null check (difficulty in ('Beginner', 'Intermediate', 'Advanced')),
  category text not null check (category in ('Beginner', 'Intermediate', 'Advanced', 'Programming')),
  duration_minutes integer not null check (duration_minutes between 1 and 180),
  content text not null check (char_length(content) between 10 and 3000),
  status text not null default 'Draft' check (status in ('Published', 'Draft')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.set_lesson_catalog_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := pg_catalog.now();
  return new;
end;
$$;
revoke all on function public.set_lesson_catalog_updated_at() from public, anon, authenticated;

drop trigger if exists lesson_catalog_updated_at on public.lesson_catalog;
create trigger lesson_catalog_updated_at before update on public.lesson_catalog
  for each row execute function public.set_lesson_catalog_updated_at();

