alter table public.lesson_catalog enable row level security;
revoke all on public.lesson_catalog from anon, authenticated;
grant select on public.lesson_catalog to anon, authenticated;
grant insert, update, delete on public.lesson_catalog to authenticated;

drop policy if exists "Readers see published lessons" on public.lesson_catalog;
create policy "Readers see published lessons"
  on public.lesson_catalog for select to anon, authenticated
  using (status = 'Published');

drop policy if exists "Admins see all lessons" on public.lesson_catalog;
create policy "Admins see all lessons"
  on public.lesson_catalog for select to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins insert lessons" on public.lesson_catalog;
create policy "Admins insert lessons"
  on public.lesson_catalog for insert to authenticated
  with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins update lessons" on public.lesson_catalog;
create policy "Admins update lessons"
  on public.lesson_catalog for update to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins delete lessons" on public.lesson_catalog;
create policy "Admins delete lessons"
  on public.lesson_catalog for delete to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

